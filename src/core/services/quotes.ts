/** 按日期取当日寄语（同日固定）。 */
export function dailyQuote(date = new Date()): string {
  const seed = date.getFullYear() * 372 + (date.getMonth() + 1) * 31 + date.getDate();
  return DAILY_QUOTES[seed % DAILY_QUOTES.length]!;
}
